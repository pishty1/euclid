import {readFileSync,writeFileSync} from 'node:fs';
const model=readFileSync(new URL('../src/rendering/figget_life_model.js',import.meta.url),'utf8');
const runtime=readFileSync(new URL('../src/rendering/figget_life_worker.js',import.meta.url),'utf8');
const source=`const engine=(()=>{const module={exports:{}};\n${model}\nreturn module.exports;})();\n${runtime}`;
const output='// Generated by scripts/generate-figget-worker.mjs; edit model/runtime instead.\nmodule.exports='+JSON.stringify(source)+';\n';
const target=new URL('../src/rendering/figget_worker_source.js',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw new Error('Run node scripts/generate-figget-worker.mjs');}
else writeFileSync(target,output);
